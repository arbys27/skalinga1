-- Youth and KK Masterlist lifecycle status and audit history.

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS status_reason text,
    ADD COLUMN IF NOT EXISTS status_changed_at timestamptz;

ALTER TABLE public.users
    DROP CONSTRAINT IF EXISTS users_status_check;

ALTER TABLE public.users
    ADD CONSTRAINT users_status_check
    CHECK (status IN ('active', 'inactive', 'suspended', 'archived'));

ALTER TABLE public.kk_masterlist
    ADD COLUMN IF NOT EXISTS status varchar(20) NOT NULL DEFAULT 'active',
    ADD COLUMN IF NOT EXISTS status_reason text,
    ADD COLUMN IF NOT EXISTS status_changed_at timestamptz;

ALTER TABLE public.kk_masterlist
    DROP CONSTRAINT IF EXISTS kk_masterlist_status_check;

ALTER TABLE public.kk_masterlist
    ADD CONSTRAINT kk_masterlist_status_check
    CHECK (status IN ('active', 'inactive', 'archived'));

CREATE TABLE IF NOT EXISTS public.youth_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer REFERENCES public.users(id) ON DELETE RESTRICT,
    masterlist_id integer REFERENCES public.kk_masterlist(id) ON DELETE RESTRICT,
    previous_status varchar(20) NOT NULL,
    new_status varchar(20) NOT NULL,
    reason text NOT NULL,
    changed_by_admin_id integer REFERENCES public.admins(id) ON DELETE SET NULL,
    changed_by_username varchar(100) NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT youth_status_history_one_record
        CHECK ((user_id IS NOT NULL AND masterlist_id IS NULL)
            OR (user_id IS NULL AND masterlist_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_youth_status_history_user
    ON public.youth_status_history (user_id, changed_at DESC);
CREATE INDEX IF NOT EXISTS idx_youth_status_history_masterlist
    ON public.youth_status_history (masterlist_id, changed_at DESC);
CREATE INDEX IF NOT EXISTS idx_kk_masterlist_status
    ON public.kk_masterlist (status);

ALTER TABLE public.youth_status_history ENABLE ROW LEVEL SECURITY;
