-- Pending borrow and return requests created after youth code verification.
-- Safe to run repeatedly after migration 015.

CREATE TABLE IF NOT EXISTS public.borrow_requests (
    request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_type text NOT NULL CHECK (service_type IN ('borrow', 'return')),
    user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    member_id varchar(50) NOT NULL,
    return_borrow_ids bigint[] NOT NULL DEFAULT '{}',
    verification_token_id bigint NOT NULL UNIQUE
        REFERENCES public.service_verification_tokens(id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Completed', 'Cancelled')),
    requested_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at timestamptz,
    processed_by_admin_id integer REFERENCES public.admins(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_borrow_requests_pending
    ON public.borrow_requests (status, service_type, requested_at DESC);
CREATE INDEX IF NOT EXISTS idx_borrow_requests_user
    ON public.borrow_requests (user_id, requested_at DESC);

ALTER TABLE public.borrow_requests ENABLE ROW LEVEL SECURITY;
